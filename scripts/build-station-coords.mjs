/**
 * Builds lib/geo/stationCoords.ts from Wikidata P5696 + datameet/railways.
 *
 * Both sources are CC0. Merge is `{...datameet, ...wikidata}` so Wikidata wins
 * on overlap (validated: of 78 conflicts over 5 km, 68 are datameet errors).
 * Datameet still covers renamed codes Wikidata dropped (BCT, CSTM); Wikidata
 * covers the current codes datameet's 2016 snapshot never saw (MMCT, CSMT).
 *
 * Usage:
 *   curl -s -G https://query.wikidata.org/sparql \
 *     -H 'Accept: text/csv' -H 'User-Agent: irctc-bwmi-build/1.0' \
 *     --data-urlencode 'query=SELECT ?s ?code ?coord WHERE { ?s wdt:P5696 ?code ; wdt:P625 ?coord . }' \
 *     -o /tmp/wd-stations.csv
 *   curl -sL https://raw.githubusercontent.com/datameet/railways/master/stations.json \
 *     -o /tmp/dm-stations.json
 *   node scripts/build-station-coords.mjs
 */
import { readFileSync, writeFileSync } from "node:fs";

const WD = process.argv[2] ?? "/tmp/wd-stations.csv";
const DM = process.argv[3] ?? "/tmp/dm-stations.json";

const CODE_RE = /^[A-Z]{2,6}$/;
const INDIA_BBOX = { minLat: 6, maxLat: 37.2, minLng: 68, maxLng: 97.5 };

const round4 = (n) => Math.round(n * 10_000) / 10_000;

function inIndia(lat, lng) {
  return lat >= INDIA_BBOX.minLat && lat <= INDIA_BBOX.maxLat && lng >= INDIA_BBOX.minLng && lng <= INDIA_BBOX.maxLng;
}

function accept(code, lat, lng) {
  return CODE_RE.test(code) && Number.isFinite(lat) && Number.isFinite(lng) && inIndia(lat, lng);
}

function parseWktPoint(wkt) {
  const match = String(wkt).match(/Point\(([-\d.]+)\s+([-\d.]+)\)/i);
  if (!match) return null;
  return { lng: Number(match[1]), lat: Number(match[2]) };
}

const datameet = {};
const dm = JSON.parse(readFileSync(DM, "utf8"));
for (const feature of dm.features ?? []) {
  const raw = String(feature.properties?.code ?? "").trim().toUpperCase();
  const [lng, lat] = feature.geometry?.coordinates ?? [];
  if (!accept(raw, lat, lng)) continue;
  datameet[raw] = { lat: round4(lat), lng: round4(lng) };
}

const wikidata = {};
const wdLines = readFileSync(WD, "utf8").split(/\r?\n/);
for (let i = 1; i < wdLines.length; i++) {
  const line = wdLines[i].trim();
  if (!line) continue;
  // s,code,coord — coord may contain commas inside quotes, but WKT has none.
  const firstComma = line.indexOf(",");
  const secondComma = line.indexOf(",", firstComma + 1);
  if (firstComma < 0 || secondComma < 0) continue;
  const code = line.slice(firstComma + 1, secondComma).trim().toUpperCase().replace(/^"|"$/g, "");
  const coord = line.slice(secondComma + 1).trim().replace(/^"|"$/g, "");
  const point = parseWktPoint(coord);
  if (!point || !accept(code, point.lat, point.lng)) continue;
  wikidata[code] = { lat: round4(point.lat), lng: round4(point.lng) };
}

const merged = { ...datameet, ...wikidata };
const rows = Object.entries(merged)
  .sort(([a], [b]) => a.localeCompare(b))
  .map(([code, { lat, lng }]) => `${code}|${lat.toFixed(4)}|${lng.toFixed(4)}`);

const table = rows.join("\n");

const output = `/**
 * Packed Indian Railways station coordinates.
 *
 * Generated by scripts/build-station-coords.mjs from:
 *   - Wikidata P5696 (Indian Railways station code) + P625
 *   - datameet/railways stations.json (2016 snapshot)
 * Both sources are CC0. Merge is datameet then Wikidata, so current codes win
 * and retired codes (BCT, CSTM) still resolve. Do not edit by hand.
 *
 *   curl -s -G https://query.wikidata.org/sparql \\\\
 *     -H 'Accept: text/csv' -H 'User-Agent: irctc-bwmi-build/1.0' \\\\
 *     --data-urlencode 'query=SELECT ?s ?code ?coord WHERE { ?s wdt:P5696 ?code ; wdt:P625 ?coord . }' \\\\
 *     -o /tmp/wd-stations.csv
 *   curl -sL https://raw.githubusercontent.com/datameet/railways/master/stations.json -o /tmp/dm-stations.json
 *   node scripts/build-station-coords.mjs
 */

const TABLE = \`
${table}
\`;

let parsed: Map<string, { lat: number; lng: number }> | null = null;

function parseTable(): Map<string, { lat: number; lng: number }> {
  const map = new Map<string, { lat: number; lng: number }>();
  for (const line of TABLE.split("\\n")) {
    const row = line.trim();
    if (!row) continue;
    const [code, lat, lng] = row.split("|");
    map.set(code, { lat: Number(lat), lng: Number(lng) });
  }
  return map;
}

export function stationCoordTable(): Map<string, { lat: number; lng: number }> {
  parsed ??= parseTable();
  return parsed;
}

/** Finite coordinates for a station code, or null — never (0, 0). */
export function lookupStationCoords(code: string): { lat: number; lng: number } | null {
  if (!code) return null;
  return stationCoordTable().get(code.trim().toUpperCase()) ?? null;
}
`;

writeFileSync("lib/geo/stationCoords.ts", output);
console.log(`datameet kept: ${Object.keys(datameet).length}`);
console.log(`wikidata kept: ${Object.keys(wikidata).length}`);
console.log(`merged unique: ${rows.length}`);
console.log(`written: ${(output.length / 1024).toFixed(1)} KB`);
