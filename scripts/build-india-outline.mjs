/**
 * Builds components/rail/indiaOutline.ts from a real boundary dataset.
 *
 * Source: datameet/maps india-composite.geojson — derived from Survey of India,
 * so the boundary is depicted as India defines it. It is 10.5 MB at full survey
 * resolution, which is obviously not shippable, so rings are simplified with
 * Ramer–Douglas–Peucker down to something that is pixel-accurate at the sizes we
 * actually draw and costs a few KB.
 *
 * The previous outline was 63 points I typed by hand. It was recognisable and
 * nothing more.
 *
 * Usage:
 *   curl -sL https://raw.githubusercontent.com/datameet/maps/master/Country/india-composite.geojson -o /tmp/india.geojson
 *   node --max-old-space-size=4096 scripts/build-india-outline.mjs /tmp/india.geojson
 */
import { readFileSync, writeFileSync } from "node:fs";

const source = process.argv[2] ?? "/tmp/india.geojson";

/**
 * Degrees. The map draws India about 600px tall across ~30° of latitude, so a
 * pixel is roughly 0.05°; this keeps the outline accurate well past that and
 * still holds up a few steps into the zoom.
 */
const MAINLAND_TOLERANCE = Number(process.env.TOLERANCE ?? 0.03);
const geo = JSON.parse(readFileSync(source, "utf8"));

/** Perpendicular distance from a point to the line through `start` and `end`. */
function perpendicular([px, py], [ax, ay], [bx, by]) {
  const dx = bx - ax;
  const dy = by - ay;
  if (dx === 0 && dy === 0) return Math.hypot(px - ax, py - ay);
  const t = ((px - ax) * dx + (py - ay) * dy) / (dx * dx + dy * dy);
  const clamped = Math.max(0, Math.min(1, t));
  return Math.hypot(px - (ax + clamped * dx), py - (ay + clamped * dy));
}

/** Ramer–Douglas–Peucker, iterative so a 242k-point ring can't blow the stack. */
function simplify(points, tolerance) {
  if (points.length < 3) return points;
  const keep = new Uint8Array(points.length);
  keep[0] = keep[points.length - 1] = 1;
  const stack = [[0, points.length - 1]];

  while (stack.length) {
    const [first, last] = stack.pop();
    let worst = 0;
    let index = -1;
    for (let i = first + 1; i < last; i++) {
      const d = perpendicular(points[i], points[first], points[last]);
      if (d > worst) {
        worst = d;
        index = i;
      }
    }
    if (worst > tolerance && index !== -1) {
      keep[index] = 1;
      stack.push([first, index], [index, last]);
    }
  }
  return points.filter((_, i) => keep[i]);
}

/** Looped rather than spread: the mainland ring has 242k points and blows the
 *  call stack if handed to Math.max(...). */
const bbox = (ring) => {
  let minX = Infinity, maxX = -Infinity, minY = Infinity, maxY = -Infinity;
  for (const [x, y] of ring) {
    if (x < minX) minX = x;
    if (x > maxX) maxX = x;
    if (y < minY) minY = y;
    if (y > maxY) maxY = y;
  }
  return { w: maxX - minX, h: maxY - minY };
};

const round = (n) => Math.round(n * 1000) / 1000;

// Flatten every polygon's outer ring; holes are irrelevant at this scale.
const rings = [];
for (const feature of geo.features) {
  const polygons = feature.geometry.type === "MultiPolygon" ? feature.geometry.coordinates : [feature.geometry.coordinates];
  for (const polygon of polygons) rings.push(polygon[0]);
}

const sized = rings
  .map((ring) => ({ ring, box: bbox(ring) }))
  // Drop slivers: anything under ~0.15° across is smaller than a map pixel here.
  .filter(({ box }) => Math.max(box.w, box.h) > 0.15)
  .sort((a, b) => b.box.w * b.box.h - a.box.w * a.box.h);

const simplified = sized
  .map(({ ring, box }, index) => {
    // The mainland carries the shape people recognise, so it keeps more detail.
    const tolerance = index === 0 ? MAINLAND_TOLERANCE : MAINLAND_TOLERANCE * 2.5;
    let out = simplify(ring, tolerance).map(([lng, lat]) => [round(lng), round(lat)]);
    // Drop consecutive duplicates left behind by rounding.
    out = out.filter((p, i) => i === 0 || p[0] !== out[i - 1][0] || p[1] !== out[i - 1][1]);
    return { points: out, box };
  })
  .filter(({ points }) => points.length >= 6);

const mainland = simplified[0].points;
const total = simplified.reduce((n, r) => n + r.points.length, 0);

const fmt = (ring) => `[${ring.map(([x, y]) => `[${x},${y}]`).join(",")}]`;

const output = `/**
 * India's boundary, for drawing routes and live train positions against.
 *
 * Generated by scripts/build-india-outline.mjs from datameet/maps
 * india-composite.geojson (Survey of India derived, so the boundary is depicted
 * as India defines it). Simplified with Ramer–Douglas–Peucker: the source is
 * 10.5 MB at full survey resolution and this is ${(JSON.stringify(simplified.map((r) => r.points)).length / 1024).toFixed(1)} KB.
 *
 * Coordinates are [lng, lat], so they run through the same \`project\` as every
 * train position and station — the map and the dots cannot drift apart.
 *
 * Do not edit by hand.
 */

/** The mainland ring. Used to frame the map, so offshore territory doesn't zoom it out. */
export const INDIA_MAINLAND: Array<[number, number]> = ${fmt(mainland)} as Array<[number, number]>;

/** Every landmass above a pixel in size: mainland plus three Andaman & Nicobar rings (not Lakshadweep). */
export const INDIA_RINGS: Array<Array<[number, number]>> = [
${simplified.map((r) => `  ${fmt(r.points)}`).join(",\n")}
] as Array<Array<[number, number]>>;

/** Equirectangular projection. Good enough at India's latitudes, and cheap. */
export function project(lng: number, lat: number): [number, number] {
  return [(lng - 67) * 10, (38 - lat) * 10];
}

const toPath = (ring: Array<[number, number]>) =>
  ring
    .map(([lng, lat], i) => {
      const [x, y] = project(lng, lat);
      return \`\${i === 0 ? "M" : "L"}\${x.toFixed(1)},\${y.toFixed(1)}\`;
    })
    .join("") + "Z";

/** All rings as one path, so a single fill draws the whole country. */
export const INDIA_PATH = INDIA_RINGS.map(toPath).join("");
`;

writeFileSync("components/rail/indiaOutline.ts", output);

console.log(`rings kept: ${simplified.length} of ${rings.length}`);
console.log(`mainland: ${rings[0].length.toLocaleString()} -> ${mainland.length.toLocaleString()} points`);
console.log(`total points: ${total.toLocaleString()}`);
console.log(`written: ${(output.length / 1024).toFixed(1)} KB`);
