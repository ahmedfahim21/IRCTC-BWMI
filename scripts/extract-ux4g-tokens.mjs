/**
 * Vendors the UX4G design-token layer into app/ux4g-tokens.css.
 *
 * We take the tokens and not the bundle: ux4g.css is 7.9 MB (3.9 MB gzipped)
 * because it carries 53 components and 3,188 utility classes this app doesn't
 * use. Shipping it would be roughly twenty-four times the size of the entire
 * application and would break the requirement that this works on a bad
 * connection. The tokens give the same government colour ramps, type scale,
 * 4 px spacing grid, radii and elevations for about 3.6 KB gzipped.
 *
 * Usage:  npx ux4g-web-components@2.0.1 …  (or npm pack, then)
 *         node scripts/extract-ux4g-tokens.mjs <path-to-ux4g.css>
 */
import { readFileSync, writeFileSync } from "node:fs";

const source = process.argv[2] ?? "node_modules/ux4g-web-components/styles/ux4g.css";
const css = readFileSync(source, "utf8");

const all = new Map();
for (const match of css.matchAll(/(--ux4g-[a-z0-9-]+)\s*:\s*([^;}]+)/g)) {
  if (!all.has(match[1])) all.set(match[1], match[2].trim());
}

/** Design tokens only — the layout, position and component groups go with the components. */
const KEEP = /^--ux4g-(color|font|ff|fs|fw|lh|line|ls|letter|space|spacing|radius|shadow|elevation|border|transition|duration|opacity|op)-/;

const kept = new Set([...all.keys()].filter((name) => KEEP.test(name)));
const queue = [...kept];
while (queue.length) {
  const value = all.get(queue.pop());
  if (!value) continue;
  for (const reference of value.matchAll(/var\((--ux4g-[a-z0-9-]+)/g)) {
    if (!kept.has(reference[1]) && all.has(reference[1])) {
      kept.add(reference[1]);
      queue.push(reference[1]);
    }
  }
}

const body = [...kept].sort().map((name) => `  ${name}: ${all.get(name)};`).join("\n");
writeFileSync(
  "app/ux4g-tokens.css",
  `/*\n * UX4G design tokens — extracted from ux4g-web-components@2.0.1, the\n * Government of India design system (MeitY).\n *\n * Generated by scripts/extract-ux4g-tokens.mjs. Do not edit by hand.\n */\n:root {\n${body}\n}\n`
);
console.log(`wrote app/ux4g-tokens.css — ${kept.size} tokens`);
